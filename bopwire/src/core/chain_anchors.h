// chain_anchors.h — the canonical chain's identity, as plain constants.
//
// Deliberately dependency-free: <cstdint> and <cstddef> only, no bopwire
// headers, nothing to link. The full node, the mini-node and the standalone
// web gateway all need to agree on which chain is real, and the gateway is
// built against librats + httplib ONLY. A shared header beats three copies
// of the same hash literal drifting apart.
//
// !! REGENERATE ALL OF THIS WITH MC_CHAIN_ID ON ANY CLEAN-SLATE FORK !!

#include <cstddef>
